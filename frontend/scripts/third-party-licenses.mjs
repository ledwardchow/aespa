import fs from "node:fs";
import path from "node:path";

export const LICENSES_FILE = "third-party-licenses.txt";

const LICENSE_FILE = /^(licen[cs]e|copying|notice)/i;

function packageRoot(moduleId) {
  const file = moduleId.replace(/^\0/, "").split("?")[0];
  const marker = `${path.sep}node_modules${path.sep}`;
  const index = file.lastIndexOf(marker);
  if (index === -1) return null;
  const parts = file.slice(index + marker.length).split(path.sep);
  const depth = parts[0].startsWith("@") ? 2 : 1;
  return file.slice(0, index + marker.length) + parts.slice(0, depth).join(path.sep);
}

function describe(root) {
  const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
  const license =
    pkg.license ?? pkg.licenses?.map((entry) => entry.type ?? entry).join(" OR ") ?? "UNKNOWN";
  const texts = fs
    .readdirSync(root)
    .filter((name) => LICENSE_FILE.test(name))
    .sort()
    .map((name) => [name, fs.readFileSync(path.join(root, name), "utf8").trim()]);
  return { name: pkg.name, version: pkg.version, license, texts };
}

// Writes the license of every npm package that ends up in the built bundle, so
// the shipped app credits the frontend code alongside the Python packages.
export function thirdPartyLicenses() {
  return {
    name: "aespa-third-party-licenses",
    apply: "build",
    generateBundle(_options, bundle) {
      const roots = new Set();
      for (const output of Object.values(bundle)) {
        if (output.type !== "chunk") continue;
        for (const id of output.moduleIds) {
          const root = packageRoot(id);
          if (root) roots.add(root);
        }
      }
      const packages = [...roots]
        .map(describe)
        .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
      const missing = packages.filter((pkg) => pkg.texts.length === 0);
      if (missing.length > 0) {
        this.warn(`No license file found for: ${missing.map((pkg) => pkg.name).join(", ")}`);
      }

      const rule = "=".repeat(78);
      const lines = [
        "FRONTEND THIRD-PARTY LICENSES",
        rule,
        "",
        "The AESPA web interface includes the following npm packages. Each is provided",
        "under its own license, reproduced below. This file is generated by the",
        "frontend build.",
        "",
        "SUMMARY",
        "-".repeat(78),
        ...packages.map((pkg) => `  ${pkg.name} ${pkg.version} — ${pkg.license}`),
        "",
        rule,
        "",
      ];
      for (const pkg of packages) {
        lines.push(`${pkg.name} ${pkg.version}`, `License: ${pkg.license}`);
        for (const [name, text] of pkg.texts) lines.push("", `----- ${name} -----`, text);
        lines.push("", rule, "");
      }
      this.emitFile({ type: "asset", fileName: LICENSES_FILE, source: lines.join("\n") });
    },
  };
}
